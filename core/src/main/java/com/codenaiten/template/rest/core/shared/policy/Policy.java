package com.codenaiten.template.rest.core.shared.policy;

public interface Policy<T> {

    void check( T candidate );

//--------------------------------------------------------------------------------------------------------------------\\
//---| DEFAULT METHODS |----------------------------------------------------------------------------------------------\\
//--------------------------------------------------------------------------------------------------------------------\\

    default boolean test( final T candidate ){
        try{
            this.check( candidate );
            return true;
        }
        catch( final Exception e ){
            return false;
        }
    }

//--------------------------------------------------------------------------------------------------------------------\\

}
